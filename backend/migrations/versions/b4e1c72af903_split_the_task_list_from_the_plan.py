#: Old namespaced tool name -> new one. The task-list tools moved category *and* shed the
#: harness's own wording (`tools/tasks.py` renames them on the way out).
_RENAMED_TOOLS = {
    "plan_write_plan": "tasks_write",
    "plan_update_task_statuses": "tasks_update_statuses",
    "plan_read_plan": "tasks_read",
}

_DISABLED_TOOLS_KEY = "tools.disabled"
_JSON = TypeAdapter(JsonValue)


def _remap_disabled_tools(mapping: dict[str, str]) -> None:
    """Rewrite every stored `tools.disabled` list through `mapping`.

    Read-modify-write per row rather than a SQL replace: the value is a JSON array, and a
    substring swap inside it would also hit a name that merely contains one of these.
    A row that will not parse is left exactly as it is — `services/tool_policy.py` already
    reads an unparseable value as "nothing disabled", and rewriting it here would be
    deciding on the operator's behalf what they had meant.
    """
    id_column = sa.column("id", sa.String)
    key_column = sa.column("key", sa.String)
    value_column = sa.column("value", sa.String)
    settings = sa.table("app_settings", id_column, key_column, value_column)
    connection = op.get_bind()
    rows = (
        connection.execute(
            sa.select(id_column, value_column).where(key_column == _DISABLED_TOOLS_KEY)
        )
        .tuples()
        .all()
    )
    for row_id, raw in rows:
        try:
            names = _JSON.validate_json(raw)
        except (TypeError, ValueError):
            continue
        if not isinstance(names, list):
            continue
        updated = sorted(
            {mapping.get(name, name) for name in names if isinstance(name, str) and name}
        )
        if updated != names:
            _ = connection.execute(
                settings.update()
                .where(id_column == row_id)
                .values(value=json.dumps(updated))
            )


